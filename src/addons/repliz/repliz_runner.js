const path = require("path");
const fs = require("fs/promises");
const chalk = require("chalk");
const { scheduleReplizVideo } = require("./repliz_api");
const { uploadToStorage } = require("./file_uploader");
const { appendRowsToSpreadsheet } = require("./spreadsheet_logger");
const { getSettings } = require("../../utils/settings_manager");

function getReplizConfig() {
    const settings = getSettings();
    const addon = settings.addons?.repliz || {};
    const rawAccounts = Array.isArray(addon.account_id) ? addon.account_id : (addon.account_id ? [addon.account_id] : []);
    const accountIds = rawAccounts
        .map((entry) => (entry && typeof entry === "object" ? entry.id : entry))
        .filter(Boolean);

    return {
        accessKey: String(addon.access_key || "").trim(),
        secretKey: String(addon.secret_key || "").trim(),
        accountIds,
        webhookUrl: String(addon.upload_webhook_url || "").trim(),
        publicBaseUrl: String(addon.upload_public_base_url || "").trim(),
        spreadsheetWebhookUrl: String(addon.spreadsheet_webhook_url || "").trim()
    };
}

function buildRangeSchedule(fileCount, scheduleSettings) {
    const today = new Date();
    const todayStr = today.toISOString().split("T")[0];
    const startDate = new Date(`${scheduleSettings.rangeStartDate || todayStr}T00:00:00`);
    const endDate = new Date(`${scheduleSettings.rangeEndDate || scheduleSettings.rangeStartDate || todayStr}T00:00:00`);

    const parseMinutes = (value, fallback) => {
        const source = value || fallback;
        const [h, m] = String(source).split(":").map(Number);
        return ((Number.isFinite(h) ? h : 0) * 60) + (Number.isFinite(m) ? m : 0);
    };

    const startMinutes = parseMinutes(scheduleSettings.rangeStart, "13:00");
    const endMinutes = parseMinutes(scheduleSettings.rangeEnd, "17:00");
    const safeStart = Math.min(startMinutes, endMinutes);
    const safeEnd = Math.max(startMinutes, endMinutes);
    const dates = [];

    for (let cursor = new Date(startDate); cursor <= endDate; cursor.setDate(cursor.getDate() + 1)) {
        dates.push(new Date(cursor));
    }

    const totalDays = Math.max(1, dates.length);
    const basePerDay = Math.floor(fileCount / totalDays);
    const extra = fileCount % totalDays;
    const scheduleTimes = [];

    dates.forEach((day, dayIndex) => {
        const itemsForDay = basePerDay + (dayIndex < extra ? 1 : 0);
        if (itemsForDay <= 0) return;

        const totalWindow = Math.max(1, safeEnd - safeStart);
        const step = totalWindow / itemsForDay;

        for (let itemIndex = 0; itemIndex < itemsForDay; itemIndex += 1) {
            const minuteOffset = safeStart + Math.floor((itemIndex + 0.5) * step);
            const scheduled = new Date(day);
            scheduled.setHours(0, 0, 0, 0);
            scheduled.setMinutes(Math.min(safeEnd, minuteOffset));
            scheduleTimes.push(scheduled);
        }
    });

    return scheduleTimes;
}

/**
 * Shared batch upload & Repliz schedule helper.
 */
async function uploadAndScheduleBatch(files, captions, scheduleTimes = [], selectedAccountIds = []) {
    const cfg = getReplizConfig();
    const accountIds = selectedAccountIds.length > 0 ? selectedAccountIds : cfg.accountIds;

    if (accountIds.length === 0) {
        console.log(chalk.red("❌ Tidak ada Repliz Account ID yang dikonfigurasi. Upload dibatalkan."));
        return;
    }

    const videosPerAccount = Math.ceil(files.length / accountIds.length);
    if (videosPerAccount > 20) {
        console.log(chalk.yellow.bold(`\n⚠️  PERINGATAN: Estimasi ${videosPerAccount} video per akun. Batas aman API Repliz mungkin terlampaui (Max 10-20/jam).`));
    }

    const usageCounter = {};
    accountIds.forEach((id) => { usageCounter[id] = 0; });

    for (let i = 0; i < files.length; i++) {
        const file = files[i];
        const baseName = path.basename(file);
        const sched = scheduleTimes[i] || scheduleTimes[0] || new Date(Date.now() + 10000);
        const caption = captions[i] || "Generated by Video Toolkit";

        const accountId = accountIds[i % accountIds.length];
        usageCounter[accountId]++;

        if (usageCounter[accountId] > 20) {
            console.log(chalk.red.bold(`⚠️  PERINGATAN SISIPAN: Akun ${accountId} telah mencapai limit 20 video!`));
        } else if (usageCounter[accountId] > 10) {
            console.log(chalk.yellow(`⚠️  Info: Akun ${accountId} telah antri ${usageCounter[accountId]} video.`));
        }

        try {
            console.log(chalk.cyan(`\n[${i + 1}/${files.length}] Menangani: ${baseName}`));
            console.log(chalk.blue(`   👤 Akun Repliz: ${accountId} (Antrian #${usageCounter[accountId]})`));

            const publicUrl = await uploadToStorage(file, {
                webhookUrl: cfg.webhookUrl,
                publicBaseUrl: cfg.publicBaseUrl
            });

            let finalSched = new Date(sched);
            if (!finalSched || isNaN(finalSched.getTime())) {
                console.log(chalk.red(`   > Skipping Repliz: Waktu tidak valid untuk ${baseName}`));
                continue;
            }

            if (finalSched < new Date()) {
                console.log(chalk.yellow(`   > Waktu ${finalSched.toLocaleString()} sudah lewat. Upload SEKARANG.`));
                finalSched = new Date();
                finalSched.setSeconds(finalSched.getSeconds() + 10);
            }

            console.log(chalk.yellow(`   > Menjadwalkan di Repliz untuk: ${finalSched.toLocaleString()}`));
            await scheduleReplizVideo(cfg.accessKey, cfg.secretKey, {
                title: `Video Content - ${baseName}`,
                description: caption,
                videoUrl: publicUrl,
                accountId,
                scheduleAt: finalSched
            });
        } catch (e) {
            console.log(chalk.red(`❌ Gagal upload/jadwal untuk ${baseName}: ${e.message}`));
        }
    }
}

async function runReplizAfterMerge({ finalVideos = [], finalDir, captions = [], uploadConfig = {} }) {
    const replizOpts = uploadConfig?.addons?.repliz;
    const hasLegacyRepliz = Boolean(uploadConfig?.replizConfig);
    const wantsSheet = replizOpts?.spreadsheet || uploadConfig?.outputMode === "video_caption_sheet";
    const wantsUpload = Boolean(replizOpts?.upload ?? hasLegacyRepliz);

    if (!replizOpts && !hasLegacyRepliz && !wantsSheet) {
        return;
    }

    const cfg = getReplizConfig();

    if (wantsSheet && finalVideos.length > 0) {
        const rows = [];
        for (let i = 0; i < finalVideos.length; i++) {
            const file = finalVideos[i];
            const caption = captions[i] || "Generated by Video Toolkit";
            const txtPath = path.join(path.dirname(file), `${path.parse(file).name}.txt`);
            await fs.writeFile(txtPath, caption, "utf8");

            let videoRef = path.resolve(file);
            try {
                videoRef = await uploadToStorage(file, {
                    webhookUrl: cfg.webhookUrl,
                    publicBaseUrl: cfg.publicBaseUrl
                });
            } catch { /* fallback to local path */ }

            rows.push({
                timestamp: new Date().toISOString(),
                video: videoRef,
                caption
            });
        }

        const sheetResult = await appendRowsToSpreadsheet(rows, {
            webhookUrl: replizOpts?.spreadsheetWebhookUrl || uploadConfig?.spreadsheetWebhookUrl || cfg.spreadsheetWebhookUrl || "",
            csvPath: path.join(finalDir, "spreadsheet_log.csv")
        });
        console.log(chalk.green(`✅ Output mode spreadsheet tersimpan via ${sheetResult.mode}: ${sheetResult.target}`));
    }

    if (wantsUpload && finalVideos.length > 0) {
        const scheduleTimes = replizOpts?.scheduleTimes || uploadConfig?.scheduleTimes || [];
        const selectedAccountIds = Array.isArray(replizOpts?.selectedReplizAccountIds)
            ? replizOpts.selectedReplizAccountIds.filter(Boolean)
            : (Array.isArray(uploadConfig?.selectedReplizAccountIds)
                ? uploadConfig.selectedReplizAccountIds.filter(Boolean)
                : []);

        console.log(chalk.cyan(`\n📤 [Addon Repliz] Memulai upload otomatis untuk ${finalVideos.length} video...`));
        await uploadAndScheduleBatch(finalVideos, captions, scheduleTimes, selectedAccountIds);
    }
}

async function processStandaloneUpload(uploadDir, scheduleSettings = {}) {
    console.log(chalk.magenta.bold(`\n--- Memulai Upload Repliz Standalone dari: ${uploadDir} ---`));

    if (!(await fs.stat(uploadDir).catch(() => false))) {
        throw new Error(`Folder tidak ditemukan: ${uploadDir}`);
    }

    const files = await fs.readdir(uploadDir);
    const videoFiles = files.filter((f) => f.endsWith(".mp4")).map((f) => path.join(uploadDir, f));

    if (videoFiles.length === 0) {
        throw new Error("Tidak ada file .mp4 di folder tersebut.");
    }

    let scheduleTimes = Array.isArray(scheduleSettings.scheduleTimes)
        ? scheduleSettings.scheduleTimes.map((t) => new Date(t))
        : [];

    if (scheduleTimes.length === 0 && scheduleSettings.scheduleMode === "range") {
        scheduleTimes = buildRangeSchedule(videoFiles.length, scheduleSettings);
    }

    let captionsMap = {};
    const captionsPath = path.join(uploadDir, "captions.json");
    if (await fs.stat(captionsPath).catch(() => false)) {
        try {
            const rawCaptions = await fs.readFile(captionsPath, "utf8");
            captionsMap = JSON.parse(rawCaptions);
            console.log(chalk.green("✅ Berhasil memuat captions.json"));
        } catch (e) {
            console.log(chalk.yellow(`⚠️ Gagal parsing captions.json: ${e.message}`));
        }
    } else {
        console.log(chalk.yellow("⚠️ File captions.json tidak ditemukan, menggunakan caption default."));
    }

    const captions = videoFiles.map((file) => {
        const data = captionsMap[path.basename(file)];
        const text = (typeof data === "object" && data !== null) ? data.caption : data;
        return text || "Video Content - Please Add Caption";
    });

    const selectedAccountIds = Array.isArray(scheduleSettings.selectedReplizAccountIds)
        ? scheduleSettings.selectedReplizAccountIds.filter(Boolean)
        : [];

    await uploadAndScheduleBatch(videoFiles, captions, scheduleTimes, selectedAccountIds);
}

module.exports = {
    getReplizConfig,
    runReplizAfterMerge,
    processStandaloneUpload
};
